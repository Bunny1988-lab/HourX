// src/store/slices/walletSlice.js
// What this file does: Manages the Time Credits and Wallet transactions state using Redux Toolkit createSlice.
// Redux concepts: createSlice, initialState, reducers, actions.

import { createSlice } from '@reduxjs/toolkit';
import { walletTransactions } from '../../data/sessions';

// Initial state for the wallet feature
const initialState = {
  credits: 4.5,
  transactions: walletTransactions
};

export const walletSlice = createSlice({
  name: 'wallet',
  initialState,
  reducers: {
    /**
     * Deducts credits when a user books a skill session and records a SPENT transaction.
     * action.payload can be a numeric cost (e.g. 1.0) or an object { cost, title }.
     */
    deductCredits: (state, action) => {
      const cost = typeof action.payload === 'object' ? action.payload.cost : action.payload;
      const title = (typeof action.payload === 'object' && action.payload.title) || 'Booked Skill Session';

      state.credits = Math.max(0, parseFloat((state.credits - cost).toFixed(1)));
      state.transactions.unshift({
        id: `tx_${Date.now()}`,
        type: 'SPENT',
        amount: `-${cost} Hour`,
        title: title,
        date: 'Just Now'
      });
    },

    /**
     * Rewards credits when a user teaches a skill and records an EARNED transaction.
     * action.payload can be a numeric amount (e.g. 1.0) or an object { amount, title }.
     */
    addCredits: (state, action) => {
      const amount = typeof action.payload === 'object' ? action.payload.amount : action.payload;
      const title = (typeof action.payload === 'object' && action.payload.title) || 'Taught New Skill Class';

      state.credits = parseFloat((state.credits + amount).toFixed(1));
      state.transactions.unshift({
        id: `tx_${Date.now()}`,
        type: 'EARNED',
        amount: `+${amount} Hour`,
        title: title,
        date: 'Just Now'
      });
    }
  }
});

// Export action creators generated by createSlice
export const { deductCredits, addCredits } = walletSlice.actions;

// Export reducer for store configuration
export default walletSlice.reducer;
